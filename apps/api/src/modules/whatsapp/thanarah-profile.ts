export function normalizeThanarahQuestion(value: string): string {
  return value
    .toLocaleLowerCase('ar')
    .replace(/[\u064b-\u065f\u0670\u0640]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim()
    .replace(/\s+/g, ' ');
}

export function isThanarahLead(value: string): boolean {
  const text = normalizeThanarahQuestion(value);
  return /\b(interested|demo|contact|subscribe|subscription|trial|sales)\b/.test(text)
    || /(مهتم|مهتمه|ارغب|اريد اشتراك|اريد تجربه|اريد عرض|اريد تواصل|ابي اشترك|ابغى اشترك|عايز اشترك|عاوز اشترك|بدي اشترك|اشتراك|تجربه|عرض سعر|طلب عرض|سعر الباقه|اسعار الباقات|اسعار|السعر|بكم|باقات|الباقه|تواصلوا معي|كلموني|اتصلوا بي|احجز عرض|حجز عرض|ابدأ الطلب|ابدا الطلب)/.test(text);
}

