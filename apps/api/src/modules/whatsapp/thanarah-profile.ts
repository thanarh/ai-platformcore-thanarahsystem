export function normalizeThanarahQuestion(value: string): string {
  return value
    .toLocaleLowerCase('ar')
    .replace(/[\u064b-\u065f\u0670\u0640]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim()
    .replace(/\s+/g, ' ');
}

export function isThanarahLead(value: string): boolean {
  const text = normalizeThanarahQuestion(value);
  return /\b(interested|demo|contact|subscribe|subscription|trial|sales)\b/.test(text)
    || /(مهتم|مهتمه|ارغب|ابي اشترك|ابغى اشترك|اشتراك|تجربه|عرض سعر|تواصلوا معي|كلموني|احجز عرض)/.test(text);
}

export function quickThanarahReply(value: string): string | null {
  const text = normalizeThanarahQuestion(value);
  if (!text) return null;

  if (/^(هلا|هلا بك|مرحبا|مرحبا بك|اهلا|اهلا بك|السلام عليكم|السلام عليكم ورحمه الله وبركاته|hi|hello|hey)$/.test(text)) {
    return 'هلا بك في ثنارة، كيف نقدر نخدمك؟';
  }

  if (isThanarahLead(value)) {
    return 'يسعدنا اهتمامك بثنارة. أرسل اسم المنشأة والمدينة وأفضل وقت للتواصل، وسيتابع معك فريقنا.';
  }

  if (/(من انتم|مين انتم|من هي ثناره|ما هي ثناره|وش ثناره|ماهو ثناره|عن ثناره|عرف ثناره)/.test(text)) {
    return 'ثنارة شركة تقنية تطوّر منظومة رقمية للمنشآت الصحية، تشمل حلولًا لإدارة العيادات والتواصل والذكاء الاصطناعي. بعض المنتجات ما زالت قيد التطوير، والفريق يوضح لك المتاح حاليًا.';
  }

  if (/(اسعار|السعر|بكم|تكلفه|التكلفه|باقات|الباقه|كم الاشتراك)/.test(text)) {
    return 'لم تُعتمد الأسعار النهائية أو تفاصيل الباقات بعد. أرسل اسم المنشأة والمدينة، وسأحوّل طلبك للفريق ليتابع معك بالمعلومات المعتمدة.';
  }

  if (/(منتجات|خدمات|تقدمون|تقدم ثناره|وش عندكم|ماذا توفرون|ماذا تقدمون)/.test(text)) {
    return 'تعمل ثنارة على ثنارة كلينك لإدارة العيادات، وThanarah AI للمساعدات الذكية، ومواقع المنشآت الصحية، وCRM والتواصل. بعض الخدمات ضمن التطوير وليست كلها متاحة تجاريًا الآن.';
  }

  if (/(متاح|جاهز|تقدرون|موجود حاليا|موجود الان|موعد الاطلاق|متى تطلقون)/.test(text)) {
    return 'تختلف حالة الإتاحة بحسب المنتج والميزة، وبعضها ما زال قيد التطوير. أخبرني بالميزة التي تحتاجها واسم منشأتك، وسأطلب من الفريق تأكيد توفرها.';
  }

  return null;
}
